"""Tile a whole country into 40 x 40 km regions (config/regions_grid.toml).

The boxes sit on the same 40 km grid as Newcastle's, and each one lists the
Geofabrik extracts it touches, using Geofabrik's own index of extract outlines.
A grid box mostly covered by a hand-made region in regions.toml is left out,
and boxes are ordered nearest-to-Newcastle first, so a queue fills in outwards.

    python -m spotfinder grid --country england
    python -m spotfinder queue --region all
"""

from __future__ import annotations

import json
import logging
import math
from pathlib import Path

import requests
import shapely
from shapely.geometry import box, shape
from shapely.ops import transform as shp_transform

from .config import CONFIG_DIR, Region, _to_bng, load_regions

log = logging.getLogger(__name__)

INDEX_URL = "https://download.geofabrik.de/index-v1.json"
GRID_FILE = CONFIG_DIR / "regions_grid.toml"
SIZE = 40_000
ORIGIN = (5_000, 25_000)  # Newcastle's box [405000, 545000, ...] sits on this grid
HOME = (425_000, 565_000)  # fill in outwards from Newcastle
COUNTRY_PARENT = {"england": "england", "wales": "united-kingdom", "scotland": "united-kingdom"}


def load_index(path: str | None = None) -> dict:
    if path:
        return json.loads(Path(path).read_text())
    r = requests.get(INDEX_URL, timeout=60)
    r.raise_for_status()
    return r.json()


def extracts(index: dict, country: str) -> dict[str, shapely.Geometry]:
    """{extract id: outline in BNG} for one UK country: England's counties, or Wales/Scotland whole."""
    out = {}
    for f in index["features"]:
        p = f["properties"]
        if country == "england" and p.get("parent") == "england" or p.get("id") == country != "england":
            out[p["id"]] = shp_transform(lambda x, y, z=None: _to_bng.transform(x, y), shape(f["geometry"]))
    return out


def plan(index: dict, country: str = "england", min_cover: float = 0.5) -> list[Region]:
    areas = extracts(index, country)
    if not areas:
        raise SystemExit(f"No Geofabrik extracts found for {country}")
    land = shapely.union_all(list(areas.values()))
    hand = [box(*r.bbox) for r in load_regions(grid=False).values()]
    xmin, ymin, xmax, ymax = land.bounds
    x0 = ORIGIN[0] + math.floor((xmin - ORIGIN[0]) / SIZE) * SIZE
    y0 = ORIGIN[1] + math.floor((ymin - ORIGIN[1]) / SIZE) * SIZE
    out = []
    for x in range(int(x0), int(xmax), SIZE):
        for y in range(int(y0), int(ymax), SIZE):
            b = box(x, y, x + SIZE, y + SIZE)
            if b.intersection(land).area < 0.05 * b.area:
                continue  # mostly sea or another country
            if any(b.intersection(h).area >= min_cover * b.area for h in hand):
                continue  # a hand-made region already covers it
            touching = sorted(k for k, g in areas.items() if g.intersects(b.buffer(1000)))
            biggest = max(touching, key=lambda k: areas[k].intersection(b).area)
            from .export import os_grid_ref

            ref = os_grid_ref(x + SIZE / 2, y + SIZE / 2, digits=2)
            name = f"{biggest.replace('-', ' ').title()} ({ref})"
            out.append(Region(key=f"g{ref.lower()}", name=name, bbox=(x, y, x + SIZE, y + SIZE), osm=tuple(touching)))
    out.sort(key=lambda r: math.hypot((r.bbox[0] + r.bbox[2]) / 2 - HOME[0], (r.bbox[1] + r.bbox[3]) / 2 - HOME[1]))
    return out


def write(regions: list[Region], path: Path = GRID_FILE) -> None:
    lines = ["# Generated by `python -m spotfinder grid`: 40 km boxes, nearest to Newcastle first.",
             "# Hand-made regions live in regions.toml; edit those, not this.", ""]
    for r in regions:
        lines += [f"[{r.key}]", f'name = "{r.name}"', f"bbox = {list(r.bbox)}",
                  "osm = [" + ", ".join(f'"{o}"' for o in r.osm) + "]", ""]
    path.write_text("\n".join(lines))
    log.info("grid: %d regions written to %s", len(regions), path)
